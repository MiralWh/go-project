func addCity(cities []string, city string) []string {
	return append(cities, city)
}

func removeCity(cities []string, city string) ([]string, bool) {
	for i, c := range cities {
		if c == city {
			// Удаляем элемент, сдвигая хвост влево
			cities = append(cities[:i], cities[i+1:]...)
			return cities, true
		}
	}
	return cities, false
}

func findCity(cities []string, city string) int {
	for i, c := range cities {
		if c == city {
			return i
		}
	}
	return -1
}
